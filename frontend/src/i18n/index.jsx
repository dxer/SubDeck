const I18nContext = createContext({
  lang: 'zh',
  setLang: () => {},
  toggleLang: () => {},
  t: (key) => key
})

function detectInitialLang() {
  const saved = localStorage.getItem(LANG_STORAGE_KEY)
  if (saved === 'zh' || saved === 'en') return saved
  const navLang = (navigator.language || '').toLowerCase()
  return navLang.startsWith('zh') ? 'zh' : 'en'
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(detectInitialLang)

  useEffect(() => {
    localStorage.setItem(LANG_STORAGE_KEY, lang)
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'
    document.title = lang === 'zh' ? 'SubDeck - 订阅聚合控制面' : 'SubDeck - Subscription Control Plane'
  }, [lang])

  const setLang = useCallback((next) => {
    if (next === 'zh' || next === 'en') {
      setLangState(next)
    }
  }, [])

  const toggleLang = useCallback(() => {
    setLangState((prev) => (prev === 'zh' ? 'en' : 'zh'))
  }, [])

  const t = useCallback(
    (key, vars) => {
      const parts = key.split('.')
      let cur = MESSAGES[lang] || MESSAGES.zh
      for (const p of parts) {
        if (cur && typeof cur === 'object' && p in cur) {
          cur = cur[p]
        } else {
          cur = null
          break
        }
      }
      if (typeof cur !== 'string') {
        let fb = MESSAGES.zh
        for (const p of parts) {
          if (fb && typeof fb === 'object' && p in fb) {
            fb = fb[p]
          } else {
            return key
          }
        }
        cur = typeof fb === 'string' ? fb : key
      }
      if (!vars) return cur
      return cur.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`))
    },
    [lang]
  )

  return (
    <I18nContext.Provider value={{ lang, setLang, toggleLang, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  return useContext(I18nContext)
}
